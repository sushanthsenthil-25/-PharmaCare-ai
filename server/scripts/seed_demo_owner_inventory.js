/**
 * Idempotently seeds realistic medicine inventory for the demo pharmacy owner (pharmacare@gmail.com).
 * Will not overwrite existing stock or duplicate records on multiple runs.
 */
export async function seedDemoOwnerInventory() {
  try {
    if (mongoose.connection.readyState !== 1) {
      await connectDB();
    }
    if (mongoose.connection.readyState !== 1) {
      console.warn('[Seed] Database disconnected. Aborting demo owner inventory seed.');
      return { success: false, error: 'Database disconnected' };
    }

    // 1. Locate Demo Pharmacy Owner Account
    const demoOwner = await User.findOne({ email: 'pharmacare@gmail.com' });
    if (!demoOwner) {
      console.warn('[Seed] Demo owner pharmacare@gmail.com not found. Please ensure users are seeded first.');
      return { success: false, error: 'Demo owner user not found' };
    }

    // 2. Locate or Create their Pharmacy
    let pharmacy = await Pharmacy.findOne({ ownerId: demoOwner._id });
    if (!pharmacy) {
      pharmacy = await Pharmacy.create({
        businessName: 'PharmaCare Central Pharmacy',
        ownerId: demoOwner._id,
        ownerName: demoOwner.name || 'PharmaCare Pharmacy Owner',
        email: demoOwner.email,
        phone: demoOwner.phone || '+91 98765 00000',
        address: 'Indiranagar, Bangalore 560038',
        latitude: 12.9784,
        longitude: 77.6408,
        openingTime: '08:00 AM',
        closingTime: '11:00 PM',
        isOpen: true,
      });
      console.log(`[Seed] Created pharmacy record for demo owner: ${pharmacy.businessName} (${pharmacy._id})`);
    }

    // 3. Idempotent Upsert for each demo medicine
    let addedCount = 0;
    let preservedCount = 0;

    for (const med of DEMO_OWNER_INVENTORY) {
      const existing = await Medicine.findOne({
        name: med.name,
        strength: med.strength,
        form: med.form,
        pharmacyId: pharmacy._id,
      });

      if (!existing) {
        await Medicine.create({
          ...med,
          pharmacyId: pharmacy._id,
          isActive: true,
        });
        addedCount++;
      } else {
        preservedCount++;
      }
    }

    const totalNow = await Medicine.countDocuments({ pharmacyId: pharmacy._id });
    console.log(
      `[Seed] Demo Owner Inventory Complete! Added: ${addedCount}, Preserved: ${preservedCount}, Total Stocked: ${totalNow} for Pharmacy: ${pharmacy.businessName}`
    );

    return {
      success: true,
      pharmacyId: pharmacy._id,
      pharmacyName: pharmacy.businessName,
      added: addedCount,
      preserved: preservedCount,
      total: totalNow,
    };
  } catch (err) {
    console.error('[Seed Error] Failed to seed demo owner inventory:', err.message);
    return { success: false, error: err.message };
  }
}

// Direct execution from CLI
if (process.argv[1]?.endsWith('seed_demo_owner_inventory.js')) {
  (async () => {
    console.log('[Seed] Starting Demo Owner Inventory Seed Script...');
    const result = await seedDemoOwnerInventory();
    console.log('[Seed Result]:', result);
    await mongoose.disconnect();
    process.exit(0);
  })();
}
